"""Regenerate documentation/openapi.json and documentation/API.md from the application code.

    cd backend && python scripts/generate_api_docs.py
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

os.environ.setdefault("APP_ENV", "test")
os.environ.setdefault("DATABASE_URL", "sqlite://")
os.environ.setdefault("JWT_SECRET_KEY", "docs-generation-only")
os.environ.setdefault("ENABLE_BACKGROUND_TASKS", "false")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from fastapi.routing import APIRoute  # noqa: E402

from app.api.routes import (  # noqa: E402
    analytics, auth, capacity, compliance, containers, dashboard, demo, incidents, integrity, monitoring, notifications,
    reports, security, settings, topology, users, vms,
)
from app.main import app  # noqa: E402

DOCS = Path(__file__).resolve().parents[2] / "documentation"


def _dep_names(dependant):
    for sub in dependant.dependencies:
        yield getattr(sub.call, "__name__", "")
        yield from _dep_names(sub)


def access_map() -> dict[tuple[str, str], str]:
    out = {}
    for module in (auth, users, dashboard, monitoring, containers, vms, security, integrity, analytics, reports, settings,
                   notifications, incidents, topology, compliance, capacity, demo):
        for r in module.router.routes:
            if not isinstance(r, APIRoute):
                continue
            names = set(_dep_names(r.dependant))
            level = "🛡️ admin" if "require_admin" in names else ("👤 user" if "get_current_user" in names else "🔓 public")
            for m in r.methods:
                out[(m.lower(), r.path)] = level
    return out


def main() -> None:
    spec = app.openapi()
    (DOCS / "openapi.json").write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    access = access_map()
    lines = [
        "# CloudGuard REST API Reference", "",
        "Generated by `backend/scripts/generate_api_docs.py` from the live OpenAPI schema "
        "([`openapi.json`](openapi.json)). Interactive docs while the backend runs: "
        "**http://127.0.0.1:8000/docs** (Swagger UI) and **/redoc**.", "",
        "**Authentication.** `POST /api/auth/login` returns an access token (30 min) and a refresh token "
        "(7 days, rotated on every use; re-use of a rotated token revokes all sessions). Send "
        "`Authorization: Bearer <access_token>`. WebSockets authenticate with `?token=<access_token>`.", "",
        "**Conventions.** Lists are paginated with `page` and `page_size` (max 200) and return "
        "`{items, total, page, page_size}`. Validation errors return `422` with `{detail, errors:[{field, message}]}`. "
        "`401` not authenticated · `403` role not permitted · `404` not found *or not visible to you* · "
        "`409` state conflict · `423` account locked · `429` rate limited · `503` optional integration unavailable.", "",
        "**Access levels.** 🔓 public · 👤 any signed-in user · 🛡️ administrator only. "
        "Container/VM actions marked 👤 additionally require the resource to be assigned to the user (admins: all).", "",
    ]
    by_tag: dict[str, list] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            by_tag.setdefault((op.get("tags") or ["System"])[0], []).append((path, method, op))
    for tag, items in by_tag.items():
        lines += [f"## {tag}", "", "| Method | Path | Access | Description |", "|---|---|---|---|"]
        for path, method, op in items:
            desc = (op.get("description") or op.get("summary") or "").split("\n")[0].replace("|", "\\|")
            lines.append(f"| `{method.upper()}` | `{path}` | {access.get((method, path), '🔓 public')} | {desc} |")
        lines.append("")
    lines += [
        "## WebSockets", "", "| Path | Access | Messages |", "|---|---|---|",
        "| `/ws/monitoring?token=…` | 👤 user | `{type: \"metric\", device_id, metric}` each collection interval; `{type: \"containers.synced\"}` |",
        "| `/ws/alerts?token=…` | 👤 user | `{type: \"alert.created\" \\| \"alert.updated\", alert}` |",
        "| `/ws/notifications?token=…` | 👤 user (own only) | `{type: \"notification.created\" \\| \"notification.updated\", notification}` |",
        "",
        "Send the text `ping` to receive `{type: \"pong\"}`.", "",
        "## Prometheus", "",
        "`GET /metrics` exposes `cloudguard_host_cpu_percent`, `_memory_percent`, `_disk_percent`, "
        "`_net_send_bytes_per_second`, `_net_recv_bytes_per_second` and `_process_count` "
        "(optionally protected with `PROMETHEUS_TOKEN`).", "",
    ]
    (DOCS / "API.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote API.md ({sum(len(v) for v in by_tag.values())} operations) and openapi.json")


if __name__ == "__main__":
    main()
